<?php
ob_start();

require_once("../config/session.php");
require_once("../config/database.php");
require_once("../library/fpdf/fpdf.php");

date_default_timezone_set("Asia/Dhaka");

$stmt = $conn->query("
SELECT
    full_name,
    roll,
    registration,
    department,
    semester,
    shift,
    section,
    session
FROM students
ORDER BY CAST(roll AS UNSIGNED) ASC
");

$students = $stmt->fetchAll(PDO::FETCH_ASSOC);
$total_students = count($students);

$pdf = new FPDF('L','mm','A4');
$pdf->SetAutoPageBreak(true,15);
$pdf->AddPage();

$pdf->SetTitle("Student List Report");
$pdf->SetAuthor("CRIMS");

// ==========================
// Professional Header (Fixed Width: 297mm for Landscape A4)
// ==========================

$logo = "../assets/images/dgpi_logo.png";

/* Blue Background Header (Full Width: 297mm) */
$pdf->SetFillColor(13,71,161);
$pdf->Rect(0,0,297,40,'F');

$pdf->SetTextColor(255,255,255);

/* Logo */
if(file_exists($logo)){
    $pdf->Image($logo,15,8,20);
}

/* Institute */
$pdf->SetXY(0,8);

$pdf->SetFont('Arial','B',17);
$pdf->Cell(297,8,'Dhaka Government Polytechnic Institute',0,1,'C');

$pdf->SetX(0);
$pdf->SetFont('Arial','',11);
$pdf->Cell(297,6,'Tejgaon, Dhaka-1208',0,1,'C');

$pdf->SetX(0);
$pdf->SetFont('Arial','B',12);
$pdf->Cell(297,6,'Department of Computer Science and Technology (CST)',0,1,'C');

$pdf->SetX(0);
$pdf->SetFont('Arial','',10);
$pdf->Cell(297,6,'Class Record & Information Management System (CRIMS)',0,1,'C');

$pdf->SetTextColor(0,0,0);

$pdf->Ln(10);

// ==========================
// Report Title
// ==========================

$pdf->SetFont('Arial','B',15);
$pdf->Cell(277,10,'Student List Report',0,1,'C');
$pdf->Ln(2);

// Report Info
$pdf->SetFillColor(240,248,255);
$pdf->SetFont('Arial','B',10);
$pdf->Cell(45,8,'Generated Date',1,0,'L',true);
$pdf->SetFont('Arial','',10);
$pdf->Cell(70,8,date("d F Y"),1,0);

$pdf->SetFont('Arial','B',10);
$pdf->Cell(35,8,'Time',1,0,'L',true);
$pdf->SetFont('Arial','',10);
$pdf->Cell(50,8,date("h:i:s A"),1,0);

$pdf->SetFont('Arial','B',10);
$pdf->Cell(35,8,'Total Students',1,0,'L',true);
$pdf->SetFont('Arial','',10);
$pdf->Cell(42,8,$total_students,1,1);

$pdf->Ln(5);

// Table Header
$pdf->SetFillColor(25,135,84);
$pdf->SetTextColor(255,255,255);
$pdf->SetFont('Arial','B',9);

$pdf->Cell(10,10,'SL',1,0,'C',true);
$pdf->Cell(18,10,'Roll',1,0,'C',true);
$pdf->Cell(55,10,'Student Name',1,0,'C',true);
$pdf->Cell(30,10,'Registration',1,0,'C',true);
$pdf->Cell(75,10,'Department',1,0,'C',true);
$pdf->Cell(25,10,'Semester',1,0,'C',true);
$pdf->Cell(22,10,'Shift',1,0,'C',true);
$pdf->Cell(20,10,'Section',1,0,'C',true);
$pdf->Cell(22,10,'Session',1,1,'C',true);

$pdf->SetTextColor(0,0,0);
$pdf->SetFont('Arial','',9);

$sl = 1;
$fill = false;

foreach($students as $row){
    if($fill){
        $pdf->SetFillColor(248,249,250);
    }else{
        $pdf->SetFillColor(255,255,255);
    }

    $pdf->Cell(10,9,$sl++,1,0,'C',true);
    $pdf->Cell(18,9,$row['roll'],1,0,'C',true);
    $pdf->Cell(55,9,$row['full_name'],1,0,'C',true);      
    $pdf->Cell(30,9,$row['registration'],1,0,'C',true);
    $pdf->Cell(75,9,$row['department'],1,0,'C',true);      
    $pdf->Cell(25,9,$row['semester'],1,0,'C',true);
    $pdf->Cell(22,9,$row['shift'],1,0,'C',true);
    $pdf->Cell(20,9,$row['section'],1,0,'C',true);
    $pdf->Cell(22,9,$row['session'],1,1,'C',true);

    $fill = !$fill;
}

// ==========================
// Footer
// ==========================

$pdf->Ln(10);
$pdf->SetFont('Arial','I',9);
$pdf->SetTextColor(120,120,120);
$pdf->Cell(277, 6, 'Generated by CRIMS | Dhaka Government Polytechnic Institute', 0, 1, 'C');

ob_end_clean();
$pdf->Output('I', 'Student_List_Report_'.date("Ymd_His").'.pdf');
exit;
?>